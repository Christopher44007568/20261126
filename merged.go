package main

import (
	"fmt"
	"path"
	"sort"
	"strings"
)

func RenderMergedScene(scene *Scene) []byte {
	var b strings.Builder
	b.WriteString("#usda 1.0\n")
	b.WriteString("# MERGED SCENE - generated by the custom Go layer stack.\n")
	b.WriteString("# An opinion is selected by declared layerStrength, never load order.\n")
	b.WriteString("# Tie break: smaller layerId, then later source line in the same layer.\n")
	b.WriteString("# Local over/def/class specifiers join child paths identically.\n(\n")
	b.WriteString("    defaultPrim = \"Stage\"\n)\n\n")

	b.WriteString("# Strength ladder (strong -> weak):\n")
	for _, layer := range scene.Layers {
		fmt.Fprintf(&b, "#   %-9s strength=%d  %s\n", layer.ID, layer.Strength, layer.File)
	}
	b.WriteString("\n")

	children := make(map[string][]*Prim)
	for _, prim := range scene.Prims {
		parent := path.Dir(prim.Path)
		if parent == "." || parent == "/" {
			parent = ""
		}
		children[parent] = append(children[parent], prim)
	}
	for parent := range children {
		sort.Slice(children[parent], func(i, j int) bool {
			return children[parent][i].Path < children[parent][j].Path
		})
	}
	writePrimChildren(&b, children, "", 0)
	return []byte(b.String())
}

func writePrimChildren(b *strings.Builder, children map[string][]*Prim, parent string, depth int) {
	for _, prim := range children[parent] {
		writePrim(b, prim)
		writePrimChildren(b, children, prim.Path, depth+1)
		writeIndent(b, depth)
		b.WriteString("}\n\n")
	}
}

func writePrim(b *strings.Builder, prim *Prim) {
	depth := pathDepth(prim.Path)
	writeIndent(b, depth)
	kind := "over"
	if prim.Defined {
		kind = "def"
	}
	typeName := prim.TypeName
	if typeName == "" {
		typeName = "Xform"
	}
	fmt.Fprintf(b, "%s %s %q {", kind, typeName, prim.Name)
	if len(prim.Specs) > 0 {
		spec := prim.Specs[0]
		fmt.Fprintf(b, "  # path=%s; strongest spec: %s(s%d, %s:%d)",
			prim.Path, spec.Layer.ID, spec.Layer.Strength, spec.File, spec.Line)
	}
	b.WriteString("\n")
	for _, name := range prim.AttrNames {
		comp := prim.Attributes[name]
		writeIndent(b, depth+1)
		fmt.Fprintf(b, "# %s opinion stack (strong -> weak):\n", name)
		for i, opinion := range comp.Opinions {
			mark := " "
			if i == 0 {
				mark = "WIN"
			}
			writeIndent(b, depth+1)
			fmt.Fprintf(b, "# [%s] %-9s s=%d  %s:%d  %s = %s\n",
				mark, opinion.LayerID, opinion.Strength, opinion.File,
				opinion.Line, name, opinion.Value)
		}
		writeIndent(b, depth+1)
		fmt.Fprintf(b, "%s %s = %s", comp.TypeName, name, comp.Winner.Value)
		fmt.Fprintf(b, "  # strongest opinion: %s (strength %d, %s:%d)\n",
			comp.Winner.LayerID, comp.Winner.Strength, comp.Winner.File, comp.Winner.Line)
	}
}

func writeIndent(b *strings.Builder, depth int) {
	b.WriteString(strings.Repeat("    ", depth))
}

func pathDepth(p string) int {
	clean := strings.Trim(p, "/")
	if clean == "" {
		return 0
	}
	return strings.Count(clean, "/")
}
