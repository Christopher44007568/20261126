package export

import (
	"image"
	"image/color"
	"strings"
)

func fillRect(img *image.RGBA, x0, y0, x1, y1 int, c color.RGBA) {
	for y := maxInt(y0, 0); y < minInt(y1, img.Bounds().Dy()); y++ {
		for x := maxInt(x0, 0); x < minInt(x1, img.Bounds().Dx()); x++ {
			img.SetRGBA(x, y, c)
		}
	}
}

func hLine(img *image.RGBA, x0, x1, y int, c color.RGBA) {
	for x := x0; x <= x1; x++ {
		img.SetRGBA(x, y, c)
	}
}

func vLine(img *image.RGBA, x, y0, y1 int, c color.RGBA) {
	for y := y0; y <= y1; y++ {
		img.SetRGBA(x, y, c)
	}
}

func drawLinePNG(img *image.RGBA, x0, y0, x1, y1 int, c color.RGBA) {
	dx := absInt(x1 - x0)
	dy := -absInt(y1 - y0)
	sx, sy := 1, 1
	if x0 > x1 {
		sx = -1
	}
	if y0 > y1 {
		sy = -1
	}
	err := dx + dy
	for {
		img.SetRGBA(x0, y0, c)
		if x0 == x1 && y0 == y1 {
			return
		}
		e2 := 2 * err
		if e2 >= dy {
			err += dy
			x0 += sx
		}
		if e2 <= dx {
			err += dx
			y0 += sy
		}
	}
}

func drawLegendPNG(img *image.RGBA, x, y int, c color.RGBA, text string) {
	fillRect(img, x, y+7, x+42, y+12, c)
	drawTinyText(img, x+52, y, text, color.RGBA{R: 32, G: 33, B: 36, A: 255}, 2)
}

func drawTinyText(img *image.RGBA, x, y int, text string, c color.RGBA, scale int) {
	if scale < 1 {
		scale = 1
	}
	cx := x
	for _, r := range strings.ToUpper(text) {
		glyph, ok := tinyFont[r]
		if !ok {
			glyph = tinyFont['?']
		}
		for row := 0; row < 7; row++ {
			for col := 0; col < 5; col++ {
				if glyph[row][col] == '#' {
					fillRect(img, cx+col*scale, y+row*scale, cx+(col+1)*scale, y+(row+1)*scale, c)
				}
			}
		}
		cx += 6 * scale
	}
}

func absInt(v int) int {
	if v < 0 {
		return -v
	}
	return v
}

func minInt(a, b int) int {
	if a < b {
		return a
	}
	return b
}

func maxInt(a, b int) int {
	if a > b {
		return a
	}
	return b
}

