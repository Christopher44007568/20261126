var wideTinyFont = map[rune][5]string{
	'N': {"1001", "1101", "1011", "1011", "1001"},
}

func TextWidth(text string, scale int) int {
	if scale < 1 {
		scale = 1
	}
	width := 0
	for _, r := range strings.ToUpper(text) {
		if _, wide := wideTinyFont[r]; wide {
			width += 5 * scale
		} else {
			width += 4 * scale
		}
	}
	return width
}

func DrawText(dst *image.RGBA, text string, x, y, scale int, c color.Color) {
	if scale < 1 {
		scale = 1
	}
	text = strings.ToUpper(text)
	cursorX := x
	for _, r := range text {
		wideGlyph, wide := wideTinyFont[r]
		glyph, ok := tinyFont[r]
		if !ok {
			glyph = tinyFont['-']
		}
		glyphWidth := 3
		advance := 4 * scale
		if wide {
			glyph = wideGlyph
			glyphWidth = 4
			advance = 5 * scale
		}
		for row := 0; row < 5; row++ {
			for col := 0; col < glyphWidth; col++ {
				if glyph[row][col] != '1' {
					continue
				}
				rect := image.Rect(
					cursorX+col*scale,
					y+row*scale,
					cursorX+(col+1)*scale,
					y+(row+1)*scale,
				)
				fillRect(dst, rect, c)
			}
		}
		cursorX += advance
	}
}
