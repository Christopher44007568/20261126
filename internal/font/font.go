const (
	glyphW  = 5
	glyphH  = 7
	advance = 6
	lineH   = 10
)

// DrawText renders s at (x,y) with integer pixel scale. Unknown characters
// become spaces. The string is upper-cased first since only capitals exist.
func DrawText(img *raster.Image8, x, y, scale int, s string, r, g, b uint8) {
	for _, ch := range s {
		if ch >= 'a' && ch <= 'z' {
			ch -= 'a' - 'A'
		}
		pat, ok := glyphs[byte(ch)]
		if !ok {
			pat = glyphs[' ']
		}
		for row := 0; row < glyphH; row++ {
			bits := pat[row]
			for col := 0; col < glyphW; col++ {
				if bits&(1<<(glyphW-1-col)) != 0 {
					for dy := 0; dy < scale; dy++ {
						for dx := 0; dx < scale; dx++ {
							img.Set(x+col*scale+dx, y+row*scale+dy, r, g, b)
						}
					}
				}
			}
		}
		x += advance * scale
	}
}

// LineHeight returns the vertical stride for text at the given scale.
func LineHeight(scale int) int { return lineH * scale }

// Measure returns the rendered width in pixels.
func Measure(s string, scale int) int { return len(s) * advance * scale }
