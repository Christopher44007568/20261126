func textWidth(text string, scale int) int {
	if text == "" {
		return 0
	}
	return (len([]rune(text))*6 - 1) * scale
}

func drawText(c *Canvas, x, y, scale int, text string, col color.RGBA) {
	cursor := x
	for _, r := range text {
		g, ok := glyphs[r]
		if !ok {
			g = glyphs[' ']
		}
		for gy, row := range g {
			for gx, ch := range row {
				if ch == '#' {
					c.Rect(cursor+gx*scale, y+gy*scale, scale, scale, col)
				}
			}
		}
		cursor += 6 * scale
	}
}

func drawTextShadow(c *Canvas, x, y, scale int, text string, col color.RGBA) {
	drawText(c, x+scale, y+scale, scale, text, color.RGBA{0, 0, 0, 210})
	drawText(c, x, y, scale, text, col)
}

func drawTextRight(c *Canvas, right, y, scale int, text string, col color.RGBA) {
	drawText(c, right-textWidth(text, scale), y, scale, text, col)
}

func drawTextCentered(c *Canvas, cx, y, scale int, text string, col color.RGBA) {
	drawText(c, cx-textWidth(text, scale)/2, y, scale, text, col)
}
