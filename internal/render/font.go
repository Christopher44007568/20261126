// DrawText renders an uppercase string with the 5x7 font, scale px per cell.
func (c *Canvas) DrawText(x, y, scale int, s string, col color.Color) {
	for i := 0; i < len(s); i++ {
		g, ok := font5x7[up(s[i])]
		if !ok {
			g = font5x7[' ']
		}
		for row := 0; row < 7; row++ {
			for cx := 0; cx < 5; cx++ {
				if g[row]&(1<<(4-cx)) != 0 {
					c.FillRect(x+i*6*scale+cx*scale, y+row*scale,
						x+i*6*scale+(cx+1)*scale, y+(row+1)*scale, col)
				}
			}
		}
	}
}

func up(b byte) byte {
	if b >= 'a' && b <= 'z' {
		return b - 32
	}
	return b
}
