const (
	glyphW   = 5
	glyphH   = 7
	glyphGap = 1
)

// drawText renders an uppercase string at (x0,y0) top-left with the given
// scale and color. Unsupported glyphs render as a blank cell.
func drawText(img *RGBImage, x0, y0, scale int, text string, c color.Color) {
	r, g, b, _ := c.RGBA()
	pc := [3]uint8{uint8(r >> 8), uint8(g >> 8), uint8(b >> 8)}
	for gi, ch := range text {
		glyph, ok := font5x7[ch]
		if !ok {
			glyph = font5x7[' ']
		}
		baseX := x0 + gi*(glyphW+glyphGap)*scale
		for row := 0; row < glyphH; row++ {
			for col := 0; col < glyphW; col++ {
				if glyph[row][col] != '#' {
					continue
				}
				for sy := 0; sy < scale; sy++ {
					for sx := 0; sx < scale; sx++ {
						px := baseX + col*scale + sx
						py := y0 + row*scale + sy
						img.set(px, py, pc)
					}
				}
			}
		}
	}
}

func textWidth(text string, scale int) int {
	if len(text) == 0 {
		return 0
	}
	return len(text)*(glyphW+glyphGap)*scale - glyphGap*scale
}
