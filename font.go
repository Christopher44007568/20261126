func Glyph(r rune) [7]string {
	if g, ok := bitmapFont[r]; ok {
		return g
	}
	if g, ok := bitmapFont[asciiUpper(r)]; ok {
		return g
	}
	return bitmapFont['?']
}

func asciiUpper(r rune) rune {
	if r >= 'a' && r <= 'z' {
		return r - 32
	}
	return r
}

func TextWidth(text string, scale int) int {
	if scale < 1 {
		scale = 1
	}
	return len([]rune(text)) * 6 * scale
}

func DrawText(c *Canvas, text string, x, y, scale int, r, g, b uint8) {
	if scale < 1 {
		scale = 1
	}
	cx := x
	for _, ch := range strings.ToUpper(text) {
		glyph := Glyph(ch)
		for row := 0; row < 7; row++ {
			for col := 0; col < 5; col++ {
				if glyph[row][col] != '#' {
					continue
				}
				for dy := 0; dy < scale; dy++ {
					for dx := 0; dx < scale; dx++ {
						c.setRGB(cx+col*scale+dx, y+row*scale+dy, r, g, b)
					}
				}
			}
		}
		cx += 6 * scale
	}
}

func DrawTextShadow(c *Canvas, text string, x, y, scale int, r, g, b uint8) {
	DrawText(c, text, x+maxInt(scale/2, 1), y+maxInt(scale/2, 1), scale, 0, 0, 0)
	DrawText(c, text, x, y, scale, r, g, b)
}

func maxInt(a, b int) int {
	if a > b {
		return a
	}
	return b
}
