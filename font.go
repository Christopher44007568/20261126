// TextWidth returns the pixel width of a string at scale 1.
func TextWidth(s string) int {
	if len(s) == 0 {
		return 0
	}
	return len(s)*(GlyphW+1) - 1
}

// DrawText renders s at (x,y) with the given color (alpha 1).
func (im *Img) DrawText(x, y int, s string, r, g, b float64) {
	im.DrawTextA(x, y, s, r, g, b, 1)
}

// DrawTextA renders s alpha-blended.
func (im *Img) DrawTextA(x, y int, s string, r, g, b, a float64) {
	cx := x
	for _, ch := range s {
		gl, ok := glyphs[ch]
		if !ok {
			gl = glyphs[' ']
		}
		for gy := 0; gy < GlyphH; gy++ {
			for gx := 0; gx < GlyphW; gx++ {
				if gl[gy][gx] == '#' {
					im.Blend(cx+gx, y+gy, r, g, b, a)
				}
			}
		}
		cx += GlyphW + 1
	}
}

// DrawTextBox draws text on a dark translucent backing for readability.
func (im *Img) DrawTextBox(x, y int, s string, r, g, b float64) {
	w := TextWidth(s)
	im.BlendRect(x-3, y-2, x+w+3, y+GlyphH+2, 0.02, 0.03, 0.05, 0.62)
	im.DrawText(x, y, s, r, g, b)
}
