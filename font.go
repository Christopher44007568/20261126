// DrawText 以 scale 放大倍数在 (x,y) 处绘制文本。
func (im *Image) DrawText(x, y, scale int, text string, c Color) {
	cx := x
	for _, r := range text {
		glyph, ok := font5x7[r]
		if !ok {
			glyph = font5x7[' ']
		}
		for gy, row := range glyph {
			for gx, b := range row {
				if b == '#' {
					im.SolidRect(cx+gx*scale, y+gy*scale, scale, scale, c)
				}
			}
		}
		cx += 6 * scale
	}
}

// TextWidth 返回给定 scale 下文本宽度（像素）。
func TextWidth(text string, scale int) int {
	if len(text) == 0 {
		return 0
	}
	return (len(text)*6 - 1) * scale
}
