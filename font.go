func drawText(img *image.NRGBA, x, y int, text string) {
	for _, r := range text {
		glyph, ok := font5x7[r]
		if !ok {
			glyph = font5x7[' ']
		}
		for row := 0; row < 7; row++ {
			bits := glyph[row]
			for col := 0; col < 5; col++ {
				if bits&(1<<(4-col)) != 0 {
					img.SetNRGBA(x+col, y+row, whitePixel)
				}
			}
		}
		x += 6
	}
}
