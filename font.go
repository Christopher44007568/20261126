func drawText(im *Image, x, y, scale int, text string, c Color) int {
	cx := x
	for _, r := range strings.ToUpper(text) {
		if r == ' ' {
			cx += 3 * scale
			continue
		}
		glyph, ok := glyph4x6[r]
		if !ok {
			glyph = glyph4x6['?']
		}
		width := 4
		if len(glyph[0]) == 5 {
			width = 5
		}
		for row, line := range glyph {
			for col, ch := range line {
				if ch != '#' {
					continue
				}
				im.FillRect(cx+col*scale, y+row*scale, scale, scale, c)
			}
		}
		cx += (width + 1) * scale
	}
	return cx
}

func textWidth(text string, scale int) int {
	width := 0
	for _, r := range strings.ToUpper(text) {
		if r == ' ' {
			width += 3 * scale
			continue
		}
		glyph, ok := glyph4x6[r]
		gw := 4
		if ok && len(glyph[0]) == 5 {
			gw = 5
		}
		width += (gw + 1) * scale
	}
	return width
}
