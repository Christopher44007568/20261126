func (im *Image) DrawText(x, y, scale int, text string, c RGB) {
	if scale < 1 {
		scale = 1
	}
	cursor := x
	for _, r := range strings.ToUpper(text) {
		glyph, ok := font5x7[r]
		if !ok {
			glyph = font5x7['?']
		}
		for gy, row := range glyph {
			for gx := 0; gx < len(row) && gx < 5; gx++ {
				if row[gx] == '1' || row[gx] == '#' {
					im.FillRect(Rect{X: cursor + gx*scale, Y: y + gy*scale, W: scale, H: scale}, c)
				}
			}
		}
		cursor += 6 * scale
	}
}

func TextWidth(text string, scale int) int {
	if len(text) == 0 {
		return 0
	}
	return len([]rune(text)) * 6 * scale
}

func (im *Image) DrawCenteredText(centerX, y, scale int, text string, c RGB) {
	im.DrawText(centerX-TextWidth(text, scale)/2, y, scale, text, c)
}
