package main

import (
	"image"
	"image/color"
)

// glyph3x5 是数字 0-9 的 3 列 x 5 行点阵，1 表示落笔。
var glyph3x5 = [10][5]string{
	{"111", "101", "101", "101", "111"}, // 0
	{"010", "110", "010", "010", "111"}, // 1
	{"111", "001", "111", "100", "111"}, // 2
	{"111", "001", "111", "001", "111"}, // 3
	{"101", "101", "111", "001", "001"}, // 4
	{"111", "100", "111", "001", "111"}, // 5
	{"111", "100", "111", "101", "111"}, // 6
	{"111", "001", "010", "010", "010"}, // 7
	{"111", "101", "111", "101", "111"}, // 8
	{"111", "101", "111", "001", "111"}, // 9
}

// drawDigit 在 (x,y) 处以 1 像素/点绘制单个数字。
func drawDigit(img *image.RGBA, digit, x, y int, c color.Color) {
	if digit < 0 || digit > 9 {
		return
	}
	for row := 0; row < 5; row++ {
		for col := 0; col < 3; col++ {
			if glyph3x5[digit][row][col] == '1' {
				img.Set(x+col, y+row, c)
			}
		}
	}
}
