func DrawText(c *Canvas, text string, x, y, scale int, color RGB) {
	if scale < 1 {
		scale = 1
	}
	cursorX := x
	for _, r := range strings.ToUpper(text) {
		glyph, ok := tinyFont[r]
		if !ok {
			glyph = tinyFont['?']
		}
		for row := 0; row < 5; row++ {
			line := glyph[row]
			for col := 0; col < len(line); col++ {
				if line[col] == '#' {
					c.FillRect(cursorX+col*scale, y+row*scale, scale, scale, color, 1)
				}
			}
		}
		cursorX += 4 * scale
	}
}

func TextWidth(text string, scale int) int {
	return len(text) * 4 * scale
}

func DrawRoundTripBadge(c *Canvas) {
	text := "ORIGINAL = RELOADED"
	width := TextWidth(text, 2) + 34
	c.FillRect(14, 14, width, 34, V(0.01, 0.015, 0.04), 0.78)
	c.FillRect(14, 14, 5, 34, V(0.10, 1.0, 0.46), 1)
	DrawText(c, text, 29, 25, 2, V(0.88, 0.98, 1.0))
}
