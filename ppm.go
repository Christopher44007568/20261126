package main

import (
	"bufio"
	"os"
)

type RGB8 struct {
	R uint8
	G uint8
	B uint8
}

type Canvas struct {
	Width  int
	Height int
	Pix    []RGB8
}

func NewCanvas(width, height int) *Canvas {
	return &Canvas{Width: width, Height: height, Pix: make([]RGB8, width*height)}
}

func (canvas *Canvas) Set(x, y int, color RGB8) {
	if x < 0 || y < 0 || x >= canvas.Width || y >= canvas.Height {
		return
	}
	canvas.Pix[y*canvas.Width+x] = color
}

func (canvas *Canvas) At(x, y int) RGB8 {
	return canvas.Pix[y*canvas.Width+x]
}

func (canvas *Canvas) Fill(color RGB8) {
	for i := range canvas.Pix {
		canvas.Pix[i] = color
	}
}

func (canvas *Canvas) FillRect(x, y, width, height int, color RGB8) {
	for py := y; py < y+height; py++ {
		for px := x; px < x+width; px++ {
			canvas.Set(px, py, color)
		}
	}
}

func linearToCanvas(frame *Image) *Canvas {
	canvas := NewCanvas(frame.Width, frame.Height)
	for i, pixel := range frame.Pix {
		canvas.Pix[i] = RGB8{
			R: clamp8(encodeSRGB(pixel.R)),
			G: clamp8(encodeSRGB(pixel.G)),
			B: clamp8(encodeSRGB(pixel.B)),
		}
	}
	return canvas
}

func writePPM(path string, canvas *Canvas) error {
	file, err := os.Create(path)
	if err != nil {
		return err
	}
	defer file.Close()

	writer := bufio.NewWriter(file)
	if _, err := writer.WriteString("P6\n"); err != nil {
		return err
	}
	if _, err := writer.WriteString("# generated by awbcompare, Go standard library only\n"); err != nil {
		return err
	}
	if _, err := writer.WriteString(itoa(canvas.Width) + " " + itoa(canvas.Height) + "\n255\n"); err != nil {
		return err
	}

	data := make([]byte, 0, len(canvas.Pix)*3)
	for _, pixel := range canvas.Pix {
		data = append(data, pixel.R, pixel.G, pixel.B)
	}
	if _, err := writer.Write(data); err != nil {
		return err
	}
	return writer.Flush()
}

func itoa(v int) string {
	if v == 0 {
		return "0"
	}
	var digits []byte
	for v > 0 {
		digits = append([]byte{byte('0' + v%10)}, digits...)
		v /= 10
	}
	return string(digits)
}
