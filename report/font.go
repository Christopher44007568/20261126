package report

import (
	"image"
	"image/color"
)

var glyphs3x5 = map[rune]string{
	' ': "000000000000000",
	'A': "010101111101101", 'B': "110101110101110", 'C': "011100100100011",
	'D': "110101101101110", 'E': "111100110100111", 'F': "111100110100100",
	'G': "011100101101011", 'H': "101101111101101", 'I': "111010010010111",
	'J': "001001001101010", 'K': "101101110101101", 'L': "100100100100111",
	'M': "101111111101101", 'N': "101111111111101", 'O': "010101101101010",
	'P': "110101110100100", 'Q': "010101101111011", 'R': "110101110101101",
	'S': "011100010001110", 'T': "111010010010010", 'U': "101101101101111",
	'V': "101101101101010", 'W': "101101111111101", 'X': "101101010101101",
	'Y': "101101010010010", 'Z': "111001010100111",
	'0': "111101101101111", '1': "010110010010111", '2': "111001111100111",
	'3': "111001011001111", '4': "101101111001001", '5': "111100111001111",
	'6': "111100111101111", '7': "111001001010010", '8': "111101111101111",
	'9': "111101111001111",
	'+': "000010111010000", '-': "000000111000000", '.': "000000000000010",
	':': "000010000010000", '/': "001001010100100", '=': "000111000111000",
	'%': "101001010100101", '>': "100010001010100", '<': "001010100010001",
}

func textWidth(text string, scale int) int {
	if text == "" {
		return 0
	}
	return (len([]rune(text))*4 - 1) * scale
}

func drawText(img *image.RGBA, x, y int, text string, scale int, c color.RGBA) int {
	cursor := x
	for _, ch := range text {
		pattern, ok := glyphs3x5[ch]
		if !ok {
			pattern = glyphs3x5[' ']
		}
		for row := 0; row < 5; row++ {
			for col := 0; col < 3; col++ {
				if pattern[row*3+col] != '1' {
					continue
				}
				for yy := 0; yy < scale; yy++ {
					for xx := 0; xx < scale; xx++ {
						set(img, cursor+col*scale+xx, y+row*scale+yy, c)
					}
				}
			}
		}
		cursor += 4 * scale
	}
	return cursor
}
