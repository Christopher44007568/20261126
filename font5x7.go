// DrawText renders an uppercase-only string onto an RGB canvas.
func DrawText(img *RGB8, x, y int, text string, r, g, b uint8) {
	for i := 0; i < len(text); i++ {
		glyph, ok := font5x7[text[i]]
		if !ok {
			if lower, ok2 := font5x7[text[i]-32]; ok2 {
				glyph = lower
			} else {
				glyph = font5x7[' ']
			}
		}
		for row := 0; row < 7; row++ {
			bits := glyph[row]
			for col := 0; col < 5; col++ {
				if bits&(1<<(4-col)) != 0 {
					px, py := x+i*6+col, y+row
					if px >= 0 && px < img.W && py >= 0 && py < img.H {
						img.Set(px, py, r, g, b)
					}
				}
			}
		}
	}
}
